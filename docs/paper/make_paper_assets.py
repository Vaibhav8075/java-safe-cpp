"""Turns results/*.json into LaTeX: generated/numbers.tex (\\res{key} look-ups) and generated/tab_*.tex.

Run after collect_results.py:  python docs/paper/make_paper_assets.py
No number in main.tex is typed by hand; a missing result makes this script fail loudly.
"""
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
RES = HERE / "results"
GEN = HERE / "generated"
GEN.mkdir(exist_ok=True)


def load(name):
    return json.loads((RES / f"{name}.json").read_text(encoding="utf-8"))


def fmt_int(n):
    s = f"{int(n):,}"
    return s.replace(",", "{,}")


def tabular(spec, header, rows):
    """Complete booktabs tabular so main.tex never has to \\input a fragment inside a table."""
    out = [rf"\begin{{tabular}}{{{spec}}}", r"\toprule", header + r" \\", r"\midrule"]
    out += rows
    out += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(out) + "\n"


numbers = {}
code, tests, audit = load("code_size"), load("tests"), load("audit")
show, heap, safety, perf = load("showcase"), load("heap"), load("safety"), load("performance")

for k, v in code.items():
    numbers[f"loc_{k}"] = fmt_int(v)
for k, v in tests.items():
    numbers[f"tests_{k}"] = fmt_int(v)
linux = load("linux_tests")
assert linux["available"] and linux["failed"] == 0, "Linux test run missing or failing"
numbers["linux_total"] = fmt_int(linux["total"])
numbers["linux_gpp"] = linux["gpp"]
for k, v in audit.items():
    numbers[f"audit_{k}"] = fmt_int(v)
assert show["python_match"], "showcase output differs from the independent Python check"
for k, v in show.items():
    numbers[f"show_{k}"] = fmt_int(v)
for k, v in heap.items():
    if k != "programs":
        numbers[f"heap_{k}"] = fmt_int(v)
numbers["heap_programs"] = fmt_int(len(heap["programs"]))
numbers["safety_demos"] = fmt_int(len(safety["demos"]))
numbers["safety_runtime"] = fmt_int(sum(d["stage"] == "run" and d["outcome"] != "completes" for d in safety["demos"]))
numbers["safety_compile"] = fmt_int(sum(d["stage"] == "compile" for d in safety["demos"]))

# ---- performance, in milliseconds
ms = lambda x: f"{x * 1000:.0f}"
numbers["startup_vm_ms"] = ms(perf["startup_vm"]["median"])
numbers["startup_native_ms"] = ms(perf["startup_native"]["median"])
numbers["bench_reps"] = fmt_int(perf["fib27"]["native"]["reps"])
ratios, opt = [], []
for b in ["fib27", "loop3m", "sort1500"]:
    p = perf[b]
    assert p["outputs_match"], f"{b}: VM and native outputs differ"
    numbers[f"{b}_native_ms"] = ms(p["native"]["median"])
    numbers[f"{b}_vmrel_ms"] = ms(p["vm_release"]["median"])
    numbers[f"{b}_vmdef_ms"] = ms(p["vm_default"]["median"])
    r = p["vm_release"]["median"] / p["native"]["median"]
    ratios.append(r)
    opt.append(p["vm_default"]["median"] / p["vm_release"]["median"])
    numbers[f"{b}_ratio"] = f"{r:.0f}"
numbers["ratio_min"], numbers["ratio_max"] = f"{min(ratios):.0f}", f"{max(ratios):.0f}"
numbers["opt_min"], numbers["opt_max"] = f"{min(opt):.0f}", f"{max(opt):.0f}"
m = perf["machine"]
numbers["cpu"] = m["cpu"].replace("(R)", "").replace("(TM)", "")
numbers["gpp"] = re.search(r"(\d+\.\d+\.\d+)\s*$", m["compiler"]).group(1)

lines = ["% generated by make_paper_assets.py - do not edit", r"\newcommand{\res}[1]{\csname res@#1\endcsname}"]
for k, v in numbers.items():
    lines.append(rf"\expandafter\def\csname res@{k}\endcsname{{{v}}}")
(GEN / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

# ---- Table: code size per module
rows = [("Lexer", "lexer"), ("Parser and AST", "parser"), ("Semantic analysis", "semantic"),
        ("Bytecode and code generator", "bytecode"), ("Virtual machine and heap", "vm"),
        ("Common and command line", None)]
body = []
for label, key in rows:
    n = code[key] if key else code["common"] + code["main"]
    body.append(rf"{label} & {fmt_int(n)} \\")
body.append(r"\midrule")
body.append(rf"Total & {fmt_int(code['total'])} \\")
(GEN / "tab_loc.tex").write_text(tabular("lr", "Component & Lines", body), encoding="utf-8")

# ---- Table: safety demos
labels = {
    "1_array_overflow": r"Store one past the end of an array",
    "2_negative_index": r"Read an array at index $-1$",
    "3_null_pointer": r"Dereference \texttt{nullptr}",
    "4_use_after_delete": r"Use a pointer after \texttt{delete}",
    "5_divide_by_zero": r"Divide by zero",
    "6_infinite_recursion": r"Recurse without a base case",
    "7_int_overflow": r"Add one to the largest \texttt{int}",
    "8_address_of": r"Take an address with \texttt{\&}",
    "9_missing_return": r"Non-void function that can end without \texttt{return}",
}
body = []
for d in safety["demos"]:
    if d["stage"] == "compile":
        result = "rejected: compile error"
        when = "compile"
    elif d["outcome"] == "completes":
        result = rf"completes, prints ${d['stdout'][-1]}$"
        when = "run"
    else:
        result = rf"\texttt{{{d['outcome']}}}"
        when = "run"
    line = d["line"] if d["line"] is not None else "--"
    body.append(rf"{labels[d['name']]} & {when} & {result} & {line} \\")
(GEN / "tab_safety.tex").write_text(
    tabular("p{5.6cm}lp{5.6cm}r", "Unsafe action & Stage & Result & Line", body), encoding="utf-8")

# ---- Table: performance
body = []
for b, label in [("fib27", r"\texttt{fib(27)}"), ("loop3m", r"loop, $3\times10^{6}$ iter."),
                 ("sort1500", r"bubble sort, 1500 items")]:
    p = perf[b]
    body.append(rf"{label} & {ms(p['native']['median'])} & {ms(p['vm_release']['median'])} & "
                rf"{ms(p['vm_default']['median'])} & {numbers[b + '_ratio']}$\times$ \\")
(GEN / "tab_perf.tex").write_text(
    tabular("lrrrr", "Benchmark & Native & VM (Rel.) & VM (def.) & Ratio", body), encoding="utf-8")
print("wrote numbers.tex and", sorted(p.name for p in GEN.glob("tab_*.tex")))
